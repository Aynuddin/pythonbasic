# 1. Variables
# Think of a variable as a labeled box where you can store data.
name = "Ayn Uddin"  # 'name' is the label, "Ayn Uddin" is what's inside the box.
age = 25            # You can also store numbers. (Feel free to change this to your real age!)

# Let's print out what's inside these variables
print("Name:", name)
print("Age:", age)

print("-------------------")

# 2. Data Types
# In Python, different types of data are handled differently. Here are the 4 main ones:

# A String (str) is text. It's always wrapped in quotes.
profession = "Developer" 

# An Integer (int) is a whole number (no decimals).
books_read = 10 

# A Float (float) is a number with a decimal point.
height = 5.9 

# A Boolean (bool) can only be True or False (like a light switch). Note the capital T!
is_learning_python = True 

# Let's print them all out:
print("Profession:", profession)
print("Books read:", books_read)
print("Height:", height)
print("Is learning Python?", is_learning_python)

print("-------------------")

# You can even ask Python to tell you what "type" of data something is using type()
print("The data type of 'height' is:", type(height))
print("The data type of 'name' is:", type(name))

